import logging
from functools import lru_cache

from pydantic import ValidationError

from app.core.config import get_settings
from app.core.errors import ValidationFailure
from app.schemas.ai import BugReportDraft
from app.services.ai.anthropic_provider import AnthropicProvider
from app.services.ai.base import FALLBACK_HINT, AIInvalidResponseError, AIProvider
from app.services.ai.mock import MockProvider
from app.services.ai.openai_provider import OpenAIProvider

logger = logging.getLogger("shiptrack.ai")


@lru_cache
def get_ai_provider() -> AIProvider:
    s = get_settings()
    if s.ai_provider == "anthropic":
        return AnthropicProvider(
            api_key=s.ai_api_key,
            model=s.ai_model,
            base_url=s.ai_base_url,
            timeout=s.ai_timeout_seconds,
        )
    if s.ai_provider == "openai":
        return OpenAIProvider(
            api_key=s.ai_api_key,
            model=s.ai_model,
            base_url=s.ai_base_url,
            timeout=s.ai_timeout_seconds,
        )
    return MockProvider()


def structure_bug_report(report: str, provider: AIProvider) -> BugReportDraft:
    """Generate a draft and validate it strictly. Never persists anything.

    Privacy: the report text is never logged or stored; only the provider name and outcome are.
    """
    limit = get_settings().ai_max_input_chars
    if len(report) > limit:
        raise ValidationFailure(f"The report is too long (maximum {limit} characters).")

    try:
        raw = provider.generate_draft(report)
        draft = BugReportDraft.model_validate(raw)
    except ValidationError:
        logger.warning("AI provider %s returned a draft that failed validation", provider.name)
        raise AIInvalidResponseError(
            "The AI service returned a draft in an unexpected format." + FALLBACK_HINT
        ) from None
    logger.info("AI draft generated by provider=%s", provider.name)
    return draft
